export function getCategoryLabel(category, t) {
  if (typeof category !== "string" || !category.trim()) {
    return "";
  }

  const original = category.trim();

  const aliases = {
    food: "Food",
    shopping: "Shopping",
    education: "Education",
    transport: "Transport",
    transportation: "Transport",
    bills: "Bills",
    entertainment: "Entertainment",
    health: "Health",
    healthcare: "Healthcare",
    medical: "Healthcare",
    rent: "Rent",
    housing: "Housing",
    groceries: "Groceries",
    salary: "Salary",
    freelance: "Freelance",
    freelancing: "Freelancing",
    business: "Business",
    investment: "Investment",
    investments: "Investment",
    gift: "Gift",
    gifts: "Gifts",
    other: "Other",
    "other expense": "Other Expense",
    "other income": "Other Income",
  };

  const normalized = original.toLowerCase().replace(/\s+/g, " ");
  const translationKey = aliases[normalized];

  if (!translationKey) {
    return original;
  }

  const key = `categoryNames.${translationKey}`;
  const translated = t(key);

  return translated && translated !== key ? translated : original;
}
